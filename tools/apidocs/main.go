// Command apidocs generates the Docusaurus API-reference pages directly
// from the Go source (go/doc), so documented signatures can never drift
// from the implementation.
//
// Usage: go run ./tools/apidocs
//
// Outputs (relative to the repository root):
//
//	website/docs/api/generated/client-methods.md
//	website/docs/api/generated/session-methods.md
//
// CI regenerates these and fails on any diff (docs workflow), making the
// generated reference a signature contract, not a copy.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/doc"
	"go/printer"

	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

var fset = token.NewFileSet()

type pkgRef struct {
	pkgPath string
	outPath string
	title   string
	pkgName string
}

func main() {
	root, err := moduleRoot()
	if err != nil {
		fatal(err)
	}
	refs := []pkgRef{
		{pkgPath: "github.com/Skryldev/suromesh/client", outPath: "website/docs/api/generated/client-methods.md", title: "Client Methods", pkgName: "client"},
		{pkgPath: "github.com/Skryldev/suromesh/session", outPath: "website/docs/api/generated/session-methods.md", title: "Session Methods", pkgName: "session"},
	}
	for _, r := range refs {
		if err := generate(root, r); err != nil {
			fatal(err)
		}
	}
	fmt.Println("apidocs: generated", len(refs), "reference pages")
}

func generate(root string, r pkgRef) error {
	dir := filepath.Join(root, strings.TrimPrefix(r.pkgPath, "github.com/Skryldev/suromesh/"))
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(fi os.FileInfo) bool {
		return !strings.HasSuffix(fi.Name(), "_test.go")
	}, parser.ParseComments)
	if err != nil {
		return err
	}
	var d *doc.Package
	for _, p := range pkgs {
		d = doc.New(p, r.pkgPath, doc.AllMethods)
	}
	if d == nil {
		return fmt.Errorf("no package at %s", dir)
	}

	var b strings.Builder
	b.WriteString("---\n")
	b.WriteString(fmt.Sprintf("title: %s (generated)\n", r.title))
	b.WriteString("sidebar_label: Generated signatures\n")
	b.WriteString("description: Machine-generated from Go source; regenerated by CI. Do not edit by hand.\n")
	b.WriteString("---\n\n")
	b.WriteString(fmt.Sprintf("# %s\n\n", r.title))
	b.WriteString("> **Autogenerated** from `" + r.pkgPath + "` by `tools/apidocs` and verified in CI.\n")
	b.WriteString("> Signatures are authoritative; descriptions are the Go doc comments.\n\n")

	// Types with methods (constructors first, then methods alphabetically).
	type namedMethods struct {
		name string
		rec  string
		m    []*doc.Func
	}
	var types []namedMethods
	for _, t := range d.Types {
		var ms []*doc.Func
		for _, m := range t.Methods {
			if !ast.IsExported(m.Name) {
				continue
			}
			ms = append(ms, m)
		}
		if len(ms) == 0 {
			continue
		}
		rec := typeName(t)
		types = append(types, namedMethods{name: t.Name, rec: rec, m: ms})
	}
	sort.Slice(types, func(i, j int) bool { return types[i].name < types[j].name })

	b.WriteString("## Constructors\n\n")
	var ctors []*doc.Func
	for _, f := range d.Funcs {
		if ast.IsExported(f.Name) && isConstructor(f, d) {
			ctors = append(ctors, f)
		}
	}
	sort.Slice(ctors, func(i, j int) bool { return ctors[i].Name < ctors[j].Name })
	if len(ctors) == 0 {
		b.WriteString("_None._\n\n")
	}
	for _, f := range ctors {
		writeFunc(&b, f, r.pkgName)
	}

	for _, t := range types {
		fmt.Fprintf(&b, "## Type `%s`\n\n", t.name)
		for _, m := range t.m {
			writeFunc(&b, m, r.pkgName)
		}
	}

	out := filepath.Join(root, r.outPath)
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return err
	}
	return os.WriteFile(out, []byte(b.String()), 0o644)
}

// typeName extracts the base type name for a doc.Type (value or pointer
// receiver forms).
func typeName(t *doc.Type) string {
	n := t.Name
	return n
}

func isConstructor(f *doc.Func, d *doc.Package) bool {
	// Heuristic: exported top-level function returning a package-local type
	// or error — documented as a constructor when it starts with New/Open/
	// Parse or returns (T, error).
	if strings.HasPrefix(f.Name, "New") || strings.HasPrefix(f.Name, "Open") ||
		strings.HasPrefix(f.Name, "Parse") {
		return true
	}
	return false
}

func writeFunc(b *strings.Builder, f *doc.Func, pkg string) {
	// Render the declaration without its doc comment, collapsed to one line.
	// doc.Func.Decl IS the *ast.FuncDecl; copy it with Doc cleared.
	var decl bytes.Buffer
	if err := printer.Fprint(&decl, fset, &ast.FuncDecl{
		Name: &ast.Ident{Name: f.Name, NamePos: f.Decl.Name.Pos()},
		Recv: f.Decl.Recv,
		Type: f.Decl.Type,
	}); err != nil {
		fmt.Fprintf(b, "### `%s`\n\n", f.Name)
		return
	}
	oneLine := strings.Join(strings.Fields(decl.String()), " ")
	fmt.Fprintf(b, "### `%s`\n\n", oneLine)
	if txt := strings.TrimSpace(f.Doc); txt != "" {
		for _, line := range strings.Split(txt, "\n") {
			// Escape MDX-sensitive characters in doc text ({ } < >).
			line = strings.ReplaceAll(line, "{", "\\{")
			line = strings.ReplaceAll(line, "}", "\\}")
			line = strings.ReplaceAll(line, "<", "\\<")
			b.WriteString(strings.TrimRight(line, " \t") + "  \n")
		}
		b.WriteString("\n")
	}
}

func moduleRoot() (string, error) {
	wd, err := os.Getwd()
	if err != nil {
		return "", err
	}
	// Walk up to find go.mod.
	dir := wd
	for i := 0; i < 6; i++ {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		dir = filepath.Dir(dir)
	}
	return "", fmt.Errorf("go.mod not found from %s", wd)
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "apidocs:", err)
	os.Exit(1)
}
