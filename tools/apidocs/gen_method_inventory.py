if missing:
    sys.exit(f"MAPPING INCOMPLETE: unmapped methods: {missing}")
extra = [k for k in M if k not in {m[0] for m in methods}]
if extra:
    sys.exit(f"MAPPING HAS PHANTOM ENTRIES: {extra}")

for name, fname, line in methods:
    cls, row, why = M[name]
    rows.append({"sdk_method": name, "sdk_source": f"client/{fname}:{line}",
                 "classification": cls, "matrix_row": row, "justification": why})

out = ROOT / "service/docs/audit/evidence/sdk-method-inventory.csv"
with out.open("w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=["sdk_method", "sdk_source", "classification", "matrix_row", "justification"])
    w.writeheader()
    w.writerows(rows)

tally = collections.Counter(r["classification"] for r in rows)
total = sum(tally.values())
