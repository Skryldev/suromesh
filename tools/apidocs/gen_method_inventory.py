for f in sorted(SRC.glob("*.go")):
    if f.name.endswith("_test.go"):
        continue
    for i, line in enumerate(f.read_text().splitlines(), 1):
        m = pat.match(line)
        if m:
            methods.append((m.group(1), f.name, i))
assert len(methods) == 73, f"expected 73 methods, found {len(methods)}"

